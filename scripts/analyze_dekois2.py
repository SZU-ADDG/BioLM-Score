def calc_metrics(compounds: pd.DataFrame) -> dict:
    ranked = compounds.sort_values("score", ascending=False, kind="mergesort").reset_index(drop=True)
    labels = ranked["label"].astype(int).to_numpy()
    scores = ranked["score"].astype(float).to_numpy()
    n = len(ranked)
    n_actives = int(labels.sum())
    n_decoys = int(n - n_actives)
    if n == 0 or n_actives == 0 or n_decoys == 0:
        raise ValueError(f"Metric input requires both classes; n={n}, actives={n_actives}")
    n_top = max(1, int(n * 0.01))
    n_top_actives = int(labels[:n_top].sum())
    expected_actives = n_actives * 0.01
    score_label_pairs = [[float(score), int(label)] for score, label in zip(scores, labels)]
    return {
        "n_compounds": n,
        "n_actives": n_actives,
        "n_decoys": n_decoys,
        "top1_count": n_top,
        "top1_actives": n_top_actives,
        "auroc": float(roc_auc_score(labels, scores)),
        "bedroc_80_5": float(CalcBEDROC(score_label_pairs, 1, 80.5)),
        "ef1_percent": float(n_top_actives / expected_actives),
    }


def max_pose(scores: pd.DataFrame, score_column: str = "score") -> pd.DataFrame:
    ordered = scores.sort_values(
        ["compound_id", score_column, "pose_id"],
        ascending=[True, False, True],
        kind="mergesort",
    )
    winners = ordered.drop_duplicates("compound_id", keep="first").copy()
    winners = winners.rename(columns={score_column: "score"})
    return winners[["compound_id", "pose_id", "label", "score"]]


def safe_corr(x: pd.Series, y: pd.Series, method: str) -> tuple[float, float, int]:
    mask = x.notna() & y.notna() & np.isfinite(x) & np.isfinite(y)
    xx = x[mask].astype(float)
    yy = y[mask].astype(float)
    if len(xx) < 3 or xx.nunique() < 2 or yy.nunique() < 2:
        return math.nan, math.nan, int(len(xx))
    result = pearsonr(xx, yy) if method == "pearson" else spearmanr(xx, yy)
    return float(result.statistic), float(result.pvalue), int(len(xx))


def bootstrap_ci(values: np.ndarray, rng: np.random.Generator, n_boot: int) -> tuple[float, float, float]:
    values = np.asarray(values, dtype=float)
    samples = rng.choice(values, size=(n_boot, len(values)), replace=True)
    means = samples.mean(axis=1)
    return float(values.mean()), float(np.quantile(means, 0.025)), float(np.quantile(means, 0.975))


def save_figure(fig: plt.Figure, path: Path) -> None:
    fig.tight_layout()
    fig.savefig(path.with_suffix(".png"), dpi=220, bbox_inches="tight")
    fig.savefig(path.with_suffix(".pdf"), bbox_inches="tight")
    plt.close(fig)


