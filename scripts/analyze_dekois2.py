def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def atomic_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")
    temporary.replace(path)


def read_tsv(path: Path) -> pd.DataFrame:
    return pd.read_csv(path, sep="\t", compression="gzip" if path.suffix == ".gz" else None)


def variant_family(variant: str) -> str:
    if variant.startswith("full_biolm_"):
        return "Full BioLM-Score"
    if variant.startswith("graph_only_"):
        return "Graph-only / GenScore"
    if variant.startswith("no_protein_lm_"):
        return "W/O protein LM"
    if variant.startswith("no_ligand_lm_"):
        return "W/O ligand LM"
    if variant.startswith("lm_only_"):
        return "LM-only"
    raise ValueError(f"Unrecognized variant: {variant}")


def variant_seed(variant: str) -> int:
    return int(variant.rsplit("seed", 1)[1])


