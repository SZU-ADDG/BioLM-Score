#!/usr/bin/env python3
"""Reproducible DEKOIS 2.0 analysis for BioLM-Score.

This script consumes pose-level scores generated by the dekois3.py-based
runtime. It does not construct graphs or run model inference. The original
screening definitions are preserved:

* one compound score = maximum score over its Glide SP poses;
* AUROC from sklearn.metrics.roc_auc_score;
* BEDROC with alpha=80.5 from RDKit;
* EF1% using the top max(1, int(N * 0.01)) ranked compounds and
  expected actives = N_active * 0.01.

The script covers checklist experiments 1/4/5/6/8/9/14/15/16/17/22/23.
Experiment 25 is intentionally omitted and SurfDock is not rerun.
"""

